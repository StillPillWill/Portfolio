import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new" });
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 });
const errs = []; p.on("pageerror", e => errs.push(e.message)); p.on("console", m => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:4174/", { waitUntil: "networkidle2", timeout: 30000 });
await new Promise(r => setTimeout(r, 1500));
const y = () => p.$$eval(".collage-track", els => els.map(e => Math.round(new DOMMatrix(getComputedStyle(e).transform).m42)));
const y1 = await y(); await p.screenshot({ path: "qa/x/collage-1.png" });
await new Promise(r => setTimeout(r, 3000)); const y2 = await y();
console.log("track Y before/after 3s:", y1.join(","), "->", y2.join(","));
console.log("moving:", y1.every((v, i) => v !== y2[i]));
console.log("tiles:", await p.$$eval(".collage-tile", e => e.length), "imgs loaded:", await p.$$eval(".collage img", e => e.filter(i => i.complete && i.naturalWidth > 0).length));
await p.mouse.move(1200, 200); await new Promise(r => setTimeout(r, 700));
console.log("parallax vars:", await p.$eval(".hero", e => e.style.getPropertyValue("--mx") + "," + e.style.getPropertyValue("--my")));
await p.screenshot({ path: "qa/x/collage-2.png" });
console.log("overflow-x:", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
await p.setViewport({ width: 390, height: 844 }); await p.reload({ waitUntil: "networkidle2" }); await new Promise(r => setTimeout(r, 1200));
await p.screenshot({ path: "qa/x/collage-m.png" });
console.log("mobile overflow-x:", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
const q = await b.newPage(); await q.emulateMediaFeatures([{ name: "prefers-reduced-motion", value: "reduce" }]); await q.setViewport({ width: 1440, height: 900 });
await q.goto("http://localhost:4174/", { waitUntil: "networkidle2" }); await new Promise(r => setTimeout(r, 800));
console.log("reduced-motion animation:", await q.$eval(".collage-track", e => getComputedStyle(e).animationName));
console.log("errors:", errs.length, errs.slice(0, 2).join(" | "));
await b.close();
